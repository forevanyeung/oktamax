import { findItems } from '../content/dom';
import {
  checkbox,
  checkboxGroup,
  note,
  radio,
  section,
  select,
  text,
  type FormView,
  type Section,
} from '../form/schema';
import { get, getAll } from '../okta/api';
import type { Authenticator } from '../okta/types';
import { STATUS } from './format';
import { objectSections } from './generic';
import type { ViewProvider } from './types';

interface AuthenticatorMethod {
  type: string;
  status: string;
  settings?: Record<string, unknown>;
}

/** Okta's authenticator dialogs are 650px wide. */
const WIDTH = 650;

const USED_FOR = 'Used for (legacy)';
const CAN_BE_USED_FOR = 'This authenticator can be used for:';

/** `settings.allowedFor`, as Email's (and Phone's / Security Question's) radio shows it. */
const ALLOWED_FOR = [
  { value: 'any', label: 'Authentication and recovery' },
  {
    value: 'recovery',
    label: 'Recovery in password policy rules',
    hint: 'The Okta account management policy is exempt from this setting.',
  },
];

const allowedForSection = (settings: Record<string, unknown> | undefined): Section =>
  section(USED_FOR, [
    typeof settings?.allowedFor === 'string' &&
      radio(CAN_BE_USED_FOR, settings.allowedFor, ALLOWED_FOR),
  ]);

/** Method types whose status is ACTIVE, i.e. the checked "User can verify with" boxes. */
const activeMethods = (methods: AuthenticatorMethod[]) =>
  methods.filter((m) => m.status === 'ACTIVE').map((m) => m.type);

type ViewBody = Omit<FormView, 'raw' | 'width'>;

function emailView(a: Authenticator): ViewBody {
  const lifetime = a.settings?.tokenLifetimeInMinutes;
  const lifetimeLabel = (v: unknown) => (v === 5 ? '5 (default)' : String(v));
  return {
    description:
      'If email is selected, Okta will send an email magic link and security token (code) to the email address enrolled by the user. The user can click on the link or enter the token (code) to gain access.',
    sections: [
      section('Settings', [
        lifetime !== undefined &&
          select('Email challenge lifetime (minutes)', String(lifetime), {
            [String(lifetime)]: lifetimeLabel(lifetime),
          }),
      ]),
      allowedForSection(a.settings),
    ],
  };
}

function googleAuthenticatorView(): ViewBody {
  return {
    description:
      "If users select Google Authenticator when signing in, they're prompted to enter a temporary code generated by their Google Authenticator App. After entering the code, users are granted access.",
    sections: [section(USED_FOR, [note(CAN_BE_USED_FOR, ['Authentication and recovery'])])],
  };
}

const OKTA_VERIFY_METHODS = [
  { value: 'totp', label: 'TOTP (on by default) (Android and iOS only)' },
  { value: 'push', label: 'Push notification (Android and iOS only)' },
  { value: 'signed_nonce', label: 'Okta FastPass (All platforms)' },
];

const OKTA_VERIFY_USER_VERIFICATION = [
  {
    value: 'PREFERRED',
    label: 'Preferred',
    hint: 'Users can choose to enable device passcode or biometric confirmation for their account',
  },
  {
    value: 'REQUIRED',
    label: 'Required',
    hint: 'Users are required to enable device passcode or biometric confirmation for their account',
  },
  {
    value: 'REQUIRED_BIOMETRICS',
    label: 'Required with biometrics only',
    hint: 'Users are required to enable biometric confirmation for their account',
  },
];

const NUMBER_CHALLENGE = {
  NEVER: 'Never',
  HIGH_RISK_ONLY: 'Only for high risk sign-in attempts',
  ALWAYS: 'All push challenges',
};

function oktaVerifyView(a: Authenticator, methods: AuthenticatorMethod[]): ViewBody {
  const s = a.settings ?? {};
  const uvMethods = Array.isArray(s.userVerificationMethods) ? s.userVerificationMethods : [];
  const userVerification =
    s.userVerification === 'REQUIRED' && uvMethods.length === 1 && uvMethods[0] === 'BIOMETRICS'
      ? 'REQUIRED_BIOMETRICS'
      : (s.userVerification as string | undefined);
  const numberChallenge = (s.channelBinding as { required?: string } | undefined)?.required;

  return {
    description:
      'After admins configure this authenticator, users are prompted to download and install the Okta Verify app. Once installed, Okta Verify uses your configuration to allow users to access protected resources.',
    sections: [
      section(USED_FOR, [
        note(CAN_BE_USED_FOR, [
          'Authentication (with time-based one-time password (TOTP), push notification, Okta FastPass)',
          'Recovery in password policy rules (with push notification only)',
        ]),
      ]),
      section('Verification options', [
        checkboxGroup('User can verify with', activeMethods(methods), OKTA_VERIFY_METHODS),
      ]),
      section(
        'Okta FastPass',
        [],
        'Sign-in page option: Enable this button through authentication policies. Choose a policy, then navigate to its user identification rules.',
      ),
      section('Device passcode or biometric user verification', [
        note(
          'Authentication: User verification during authentication is enforced by authentication policy rules. How it works:',
          [
            'If user verification during authentication is enforced, users must confirm their device passcode or biometrics during Okta FastPass or push authentication',
            'User verification allows users to provide two factors in a single authentication flow',
            'Biometrics and passcodes vary by device and operating system. Examples include fingerprint, PIN, or passwords',
          ],
        ),
        !!userVerification &&
          radio(
            'Enrollment',
            userVerification,
            OKTA_VERIFY_USER_VERIFICATION,
            'You can enforce user verification enrollment, which may help reduce user friction by meeting authentication policy rules ahead of time.',
          ),
      ]),
      section(
        'Push notification: number challenge',
        [
          note('Ensure users can see the number challenge instructions', [
            'If your org is using a customized Sign-In Widget, the widget version must be 3.3.0 or higher',
            'If your org is calling the Authentication API directly, update your code to handle the number challenge API response',
          ]),
          !!numberChallenge &&
            radio('Number challenge for Okta Verify push', numberChallenge, NUMBER_CHALLENGE),
        ],
        'Choose when to present users a number challenge with an Okta Verify push challenge. If a number challenge is triggered, users are prompted to open Okta Verify and select a number that matches a number shown in the sign-in instructions. Verification succeeds only if the numbers match. This helps prevent phishing by ensuring that the user possesses both Okta Verify and the device initiating the sign-in attempt. Supported on Android and iOS.',
      ),
    ],
  };
}

const webauthnUserVerification = (step: 'enrollment' | 'authentication') => [
  {
    value: 'REQUIRED',
    label: 'Required',
    hint: `Checked and required. Authenticators without user verification support are denied ${step}.`,
  },
  { value: 'PREFERRED', label: 'Preferred', hint: 'Checked if supported by the authenticator.' },
  { value: 'DISCOURAGED', label: 'Discouraged', hint: 'Not checked.' },
];

function webauthnView(a: Authenticator, methods: AuthenticatorMethod[]): ViewBody {
  // The settings live on the webauthn method; older orgs may have them on the authenticator.
  const s = methods.find((m) => m.type === 'webauthn')?.settings ?? a.settings ?? {};
  const str = (v: unknown) => (typeof v === 'string' ? v : undefined);
  const residentKey = str(s.residentKeyRequirement);
  const enrollment = str(s.userVerification);
  const authentication = str(s.userVerificationForVerify);

  return {
    description:
      'The Passkey (WebAuthn) authenticator lets users authenticate with a security key or a biometric method, such as a fingerprint or face recognition. After you enable this authenticator, users can select it when they sign in to Okta or use it for extra authentication.',
    sections: [
      section('Credential settings', [
        residentKey !== undefined &&
          checkbox(
            'Create passkeys',
            residentKey === 'REQUIRED',
            'When enabled, the authenticator always creates passkeys (Resident Key value is set to required). When disabled (Resident Key value is set to discouraged) some authenticators may create passkeys and others may create legacy U2F credentials which can cause inconsistency in user experience. Note: passkeys specific features will be unavailable when disabled.',
          ),
      ]),
      section(
        'User verification',
        [
          !!enrollment && radio('Enrollment', enrollment, webauthnUserVerification('enrollment')),
          !!authentication &&
            radio('Authentication', authentication, webauthnUserVerification('authentication')),
        ],
        'Performs an additional check to satisfy a knowledge factor or biometric factor. This setting makes the credential multi-factor. Note: user verification for authentication can also be set in Authentication Policies. The setting here is a default and minimum requirement. When there is a conflict between settings, the highest security requirement is respected.',
      ),
    ],
  };
}

function phoneView(a: Authenticator, methods: AuthenticatorMethod[]): ViewBody {
  return {
    sections: [
      section('Verification options', [
        checkboxGroup('User can verify with', activeMethods(methods), {
          sms: 'SMS',
          voice: 'Voice call',
        }),
      ]),
      allowedForSection(a.settings),
    ],
  };
}

function securityQuestionView(a: Authenticator): ViewBody {
  return { sections: [allowedForSection(a.settings)] };
}

/** Anything without a dedicated view (Password, IdP, Duo, ...): the settings as-is. */
function genericView(a: Authenticator, methods: AuthenticatorMethod[]): ViewBody {
  return {
    sections: [
      section(undefined, [text('Name', a.name), select('Status', a.status, STATUS)]),
      ...objectSections('Settings', a.settings),
      ...objectSections('Provider', a.provider?.configuration),
      ...methods.flatMap((m) => [
        section(`Method: ${m.type}`, [select('Status', m.status, STATUS)]),
        ...objectSections(`Method: ${m.type}`, m.settings),
      ]),
    ],
  };
}

function viewBody(a: Authenticator, methods: AuthenticatorMethod[]): ViewBody {
  switch (a.key) {
    case 'okta_email':
      return emailView(a);
    case 'google_otp':
      return googleAuthenticatorView();
    case 'okta_verify':
      return oktaVerifyView(a, methods);
    case 'webauthn':
      return webauthnView(a, methods);
    case 'phone_number':
      return phoneView(a, methods);
    case 'security_question':
      return securityQuestionView(a);
    default:
      return genericView(a, methods);
  }
}

/**
 * Security › Authenticators › "Edit". Mirrors each authenticator's own edit
 * dialog (Email, Okta Verify, Passkey, ...); unknown ones fall back to a
 * generic dump of their settings.
 */
export async function authenticatorView(authenticator: Authenticator): Promise<FormView> {
  const methods = await get<AuthenticatorMethod[]>(
    `/api/v1/authenticators/${authenticator.id}/methods`,
  ).catch(() => []);

  return {
    ...viewBody(authenticator, methods),
    width: WIDTH,
    raw: { authenticator, methods },
  };
}

/** The console's labels where they differ from the API's `name`, by authenticator key. */
const CONSOLE_NAMES: Record<string, string[]> = {
  webauthn: ['Passkey (FIDO2 WebAuthn)', 'FIDO2 (WebAuthn)'],
};

/** Okta's dialog title is just the authenticator's console name. */
export const consoleName = (a: Pick<Authenticator, 'key' | 'name'>): string =>
  CONSOLE_NAMES[a.key]?.[0] ?? a.name;

export const authenticatorsProvider: ViewProvider = {
  name: 'Authenticators',
  matches: (url) => /^\/admin\/access\/(multifactor|authenticators)/.test(url.pathname),
  async findTargets() {
    const authenticators = await getAll<Authenticator>('/api/v1/authenticators');
    return findItems(authenticators, (a) => [a.name, ...(CONSOLE_NAMES[a.key] ?? [])]).map(
      ({ item, anchor, scope }) => ({
        key: `authenticator:${item.id}`,
        title: consoleName(item),
        anchor,
        scope,
        actions: scope.querySelector('.authenticator-actions'),
        menu: { icons: true },
        load: () => authenticatorView(item),
      }),
    );
  },
};
